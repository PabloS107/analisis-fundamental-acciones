def normalize_label(label):
    """Normaliza texto eliminando notas al pie, par values y caracteres tipográficos."""
    if not label:
        return ""
    s = str(label).strip()
    s = s.replace('\xa0', ' ').replace('’', "'").replace('–', '-').replace('—', '-')
    s = re.sub(r'\s*\((?:Note|Notes)\s*\d+[^)]*\)', '', s, flags=re.IGNORECASE)
    s = re.sub(r'\s*\((?:in shares|shares|usd per share|in dollars per share|per share)\)', '', s, flags=re.IGNORECASE)
    s = re.sub(r'\s*\[abstract\]', '', s, flags=re.IGNORECASE)
    s = re.sub(r'\s*\(included[^)]*\)', '', s, flags=re.IGNORECASE)
    s = re.sub(r',\s*par value.*$', '', s, flags=re.IGNORECASE)
    s = re.sub(r'\s*\(authorized\s*\d+.*$', '', s, flags=re.IGNORECASE)
    s = re.sub(r':$', '', s).strip()
    return s


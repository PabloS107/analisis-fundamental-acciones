def clean_accounting_label(label: str) -> str:
    """Limpia anotaciones de notas de los estados financieros oficiales."""
    if not label:
        return ""
    s = str(label).replace("\xa0", " ").replace("\ufffd", "-").strip()
    s = re.sub(r"\(refer to [^)]+\)", "", s, flags=re.IGNORECASE)
    s = re.sub(r"\(Notes?\s*[\d\s,and]+\)", "", s, flags=re.IGNORECASE)
    s = re.sub(r"\(included\s+[^)]+\)", "", s, flags=re.IGNORECASE)
    s = re.sub(r"\(amortized cost:[^)]+\)", "", s, flags=re.IGNORECASE)
    s = re.sub(r"\(cost:[^)]+\)", "", s, flags=re.IGNORECASE)
    s = re.sub(r"\(net of allowances[^)]+\)", "", s, flags=re.IGNORECASE)
    s = re.sub(r"-\s*see\s+Note\s*\d+", "", s, flags=re.IGNORECASE)
    s = re.sub(r"\s+", " ", s).strip()
    return s

def get_spanish_clarification(label: str, concept: str = None) -> str:
    """
    Retorna la aclaración técnica en español para una partida contable.
    Si no encuentra coincidencia directa en el diccionario, aplica normalización de notas,
    reglas semánticas por taxonomía contable o mapeo por concepto XBRL.
    """
    if not label:
        return None

    lbl_clean = clean_accounting_label(label)
    lbl_lower = lbl_clean.lower()

    # 1. Búsqueda directa exacta
    if lbl_lower in SPANISH_CLARIFICATIONS:
        return SPANISH_CLARIFICATIONS[lbl_lower]

    # 2. Sin dos puntos finales
    lbl_no_colon = lbl_lower.rstrip(":")
